import SwiftUI

extension Tokens {
    public enum Size {
        /// Height of buttons and the search field, and both sides of an icon button: the minimum touch target.
        public static let controlHeight: CGFloat = 44
        /// Side of the square thumbnail in a list card.
        public static let thumbSize: CGFloat = 88
        /// Default icon size inside controls and spec rows.
        public static let iconSize: CGFloat = 20
    }
}
